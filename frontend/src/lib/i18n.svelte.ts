const dictionaries: Record<Locale, Record<string, string>> = { en, vi }

const state = $state<{ locale: Locale }>({ locale: initialLocale() })

export function getLocale(): Locale {
  return state.locale
}

export function setLocale(locale: Locale): void {
  state.locale = locale
  try {
    localStorage.setItem(LOCALE_STORAGE_KEY, locale)
  } catch {
    // Ignore persistence failures; the in-memory locale still applies.
  }
}

export function toggleLocale(): void {
  setLocale(state.locale === 'en' ? 'vi' : 'en')
}

/** BCP 47 tag for Intl APIs (dates, numbers) matching the active locale. */
export function localeTag(): string {
  return state.locale === 'vi' ? 'vi-VN' : 'en-US'
}

export function t(key: string, params?: TranslateParams): string {
  const dict = dictionaries[state.locale] ?? en
  let text = dict[key] ?? en[key] ?? key
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value))
    }
  }
  return text
}
